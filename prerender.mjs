import esbuild from "esbuild";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import os from "node:os";
import { DEPLOYMENT_CONFIG } from "./deployment-config.mjs";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const tmp = mkdtempSync(path.join(os.tmpdir(), "wy-prerender-"));
const ssrFile = path.join(tmp, "ssr.cjs");

await esbuild.build({
  stdin: {
    contents: [
      'import { renderToString } from "react-dom/server";',
      'import { createElement } from "react";',
      'import { App } from "./app.jsx";',
      'export { SEO } from "./seo.js";',
      'export const renderPage = (page, locale, basePath) => renderToString(createElement(App, { page, locale, basePath }));',
    ].join("\n"),
    resolveDir: ROOT,
    sourcefile: "ssr-entry.jsx",
    loader: "jsx",
  },
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  outfile: ssrFile,
  legalComments: "none",
});

const require = createRequire(import.meta.url);
let SEO;
let renderPage;
try {
  ({ SEO, renderPage } = require(ssrFile));
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const esc = (value) => String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const jsonLd = (value) => `<script type="application/ld+json">${JSON.stringify(value).replace(/</g, "\\u003c")}</script>`;
const template = readFileSync(path.join(ROOT, "template.html"), "utf8").replace(/\r\n/g, "\n");
const banner = "<!-- GENERATED by prerender.mjs from template.html. Do not edit directly. -->";
const appBundleHash = createHash("sha256").update(readFileSync(path.join(ROOT, "assets/app.bundle.js"))).digest("hex").slice(0, 8);
const APP_LOADER_SCRIPT = `addEventListener("load",()=>{const load=()=>{const script=document.createElement("script");script.src="/assets/app.bundle.js?v=${appBundleHash}";document.head.append(script)};"requestIdleCallback" in window?requestIdleCallback(load,{timeout:1200}):setTimeout(load,0)},{once:true})`;
/* Homepage only. Runs before first paint and marks the page as scripted, so tab panels start collapsed without a flash.
   When the homepage script never runs (blocked, failed to load) the mark is taken back and the page keeps its static
   layout with every panel open. Without JavaScript the mark is never set. Its hash is added to the page policy below. */
const HOME_FLAG_SCRIPT = `(function(r){r.classList.add("scripted");document.addEventListener("DOMContentLoaded",function(){r.classList.contains("js")||r.classList.remove("scripted")})})(document.documentElement)`;
const assetHash = (value) => createHash("sha256").update(value).digest("hex").slice(0, 8);

/* The homepage is static HTML from home/render.cjs, with its own stylesheet and script (assets/home/). */
const { renderHome } = require("./home/render.cjs");
const { extractStyles, styleRules, VALLEY_CSS } = require("./home/lib.cjs");
const readText = (file) => readFileSync(path.join(ROOT, file), "utf8").replace(/\r\n/g, "\n");
const homeData = { repos: JSON.parse(readText("data/github.json")), year: JSON.parse(readText("assets/commit-maps/year.json")) };
const homeClasses = new Map();
const HOME_HTML = Object.fromEntries(["en", "zh-TW"].map((locale) => [locale, extractStyles(renderHome({ locale, ...homeData }), homeClasses)]));
const homeCssSource = [...["fonts", "base", "blocks", "tiles"].map((name) => readText(`home/css/${name}.css`)), VALLEY_CSS, readText("home/css/site.css"), styleRules(homeClasses)].join("\n");
const homeCss = (await esbuild.transform(homeCssSource, { loader: "css", minify: true, legalComments: "none" })).code;
const homeJsSource = ["main", "activity", "path"].map((name) => readText(`home/client/${name}.js`)).join("\n");
const homeJs = (await esbuild.transform(homeJsSource, { loader: "js", minify: true, target: "es2019", legalComments: "none" })).code;
mkdirSync(path.join(ROOT, "assets/home"), { recursive: true });
writeFileSync(path.join(ROOT, "assets/home/home.css"), homeCss);
writeFileSync(path.join(ROOT, "assets/home/home.js"), homeJs);
const innerCss = (await esbuild.transform(readText("home/css/inner.css"), { loader: "css", minify: true, legalComments: "none" })).code;
writeFileSync(path.join(ROOT, "assets/home/inner.css"), innerCss);
globalThis.__HOME_HTML__ = HOME_HTML;
const HOME_STYLES = [
  '  <link rel="preload" href="/assets/fonts/bricolage-grotesque-latin-wght-normal.woff2" as="font" type="font/woff2" crossorigin>',
  `  <link rel="stylesheet" href="/assets/home/home.css?v=${assetHash(homeCss)}">`,
  `  <script defer src="/assets/home/home.js?v=${assetHash(homeJs)}"></script>`,
].join("\n");
const SITE_STYLES = [
  '  <link rel="stylesheet" href="/styles.css">',
  '  <link rel="stylesheet" href="/editorial.css">',
  '  <link rel="stylesheet" href="/features/editorial/interactions.css">',
  `  <link rel="stylesheet" href="/assets/home/inner.css?v=${assetHash(innerCss)}">`,
].join("\n");
const cspHash = (value) => `'sha256-${createHash("sha256").update(value).digest("base64")}'`;
const aiEndpoint = process.env.PORTFOLIO_AI_ENDPOINT || DEPLOYMENT_CONFIG.aiEndpoint;
const turnstileSiteKey = process.env.TURNSTILE_SITE_KEY || DEPLOYMENT_CONFIG.turnstileSiteKey;
let aiOrigin = "";
try { aiOrigin = aiEndpoint ? new URL(aiEndpoint).origin : ""; } catch { throw new Error("PORTFOLIO_AI_ENDPOINT must be an absolute HTTPS URL"); }
if (aiOrigin && !aiOrigin.startsWith("https://")) throw new Error("PORTFOLIO_AI_ENDPOINT must use HTTPS");

function contentSecurityPolicy(headExtra, page) {
  const inlineScripts = [...headExtra.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map((match) => match[1]);
  const scriptHashes = [APP_LOADER_SCRIPT, ...inlineScripts].map(cspHash).join(" ");
  return [
    "default-src 'self'",
    `script-src 'self' 'wasm-unsafe-eval' ${scriptHashes}${turnstileSiteKey ? " https://challenges.cloudflare.com" : ""}`,
    "style-src 'self'",
    "img-src 'self' data:",
    "font-src 'self'",
    /* the homepage reads the daily commit counts from the repository */
    `connect-src 'self' https://huggingface.co https://us.aws.cdn.hf.co${page === "home" ? " https://raw.githubusercontent.com/WenyuChiou/wenyuchiou.github.io/standalone-portfolio/assets/commit-maps/year.json" : ""}${aiOrigin ? ` ${aiOrigin}` : ""}`,
    ...(turnstileSiteKey ? ["frame-src https://challenges.cloudflare.com"] : []),
    "worker-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "upgrade-insecure-requests",
  ].join("; ");
}

function extraHead(meta) {
  const parts = [];
  if (meta.page === "home") parts.push(`<script>${HOME_FLAG_SCRIPT}</script>`);
  if (meta.page.startsWith("case:")) {
    const assets = JSON.parse(readFileSync(path.join(ROOT, "assets/provenance/manifest.json"), "utf8"));
    parts.push(`<link rel="stylesheet" href="${assets.css}">`);
  }
  if (["home", "about", "hire"].includes(meta.page)) {
    parts.push(jsonLd(SEO.person));
  }
  if (SEO.pageSchemas[meta.path]) parts.push(jsonLd(SEO.pageSchemas[meta.path]));
  if (SEO.breadcrumbs[meta.path]) parts.push(jsonLd(SEO.breadcrumbs[meta.path]));
  if (SEO.citationMeta.paths.includes(meta.path)) {
    for (const [name, raw] of Object.entries(SEO.citationMeta.tags)) {
      for (const value of Array.isArray(raw) ? raw : [raw]) parts.push(`<meta name="${name}" content="${esc(value)}">`);
    }
    parts.push(jsonLd(SEO.article));
  }
  if (SEO.techArticles[meta.path]) parts.push(jsonLd(SEO.techArticles[meta.path]));
  return parts.map((part) => `  ${part}`).join("\n");
}

const generated = [];
for (const meta of Object.values(SEO.routes)) {
  const appHtml = renderPage(meta.page, meta.locale, meta.basePath);
  if (!appHtml.includes("<h1")) throw new Error(`Route ${meta.path} rendered without an h1`);
  const headExtra = extraHead(meta);
  const english = meta.locale === "en" ? meta.canonical : meta.alternate;
  const chinese = meta.locale === "zh-TW" ? meta.canonical : meta.alternate;
  const values = {
    LANG: meta.lang,
    DATA_LANG: meta.locale === "zh-TW" ? "zh" : "en",
    STYLES: meta.page === "home" ? HOME_STYLES : SITE_STYLES,
    TITLE: meta.title,
    DESCRIPTION: meta.description,
    CANONICAL: meta.canonical,
    HREFLANG_EN: english,
    HREFLANG_ZH: chinese,
    HREFLANG_DEFAULT: meta.xDefault,
    OG_TYPE: meta.ogType,
    OG_LOCALE: meta.ogLocale,
    OG_IMAGE: SEO.siteUrl + (meta.ogImage || SEO.ogImage.file),
    OG_IMAGE_ALT: meta.ogImageAlt || (meta.page.startsWith("article:") ? meta.title : SEO.ogImage.alt),
    AI_ENDPOINT: aiEndpoint,
    TURNSTILE_SITE_KEY: turnstileSiteKey,
    CSP: contentSecurityPolicy(headExtra, meta.page),
    HEAD_EXTRA: headExtra,
    APP_LOADER_SCRIPT,
    PAGE: meta.page,
    LOCALE: meta.locale,
    BASE_PATH: meta.basePath,
    APP_HTML: appHtml,
  };
  let html = template.replace(/<!-- template\.html[^\n]*-->/, banner);
  for (const [key, raw] of Object.entries(values)) {
    const value = ["APP_HTML", "HEAD_EXTRA", "STYLES", "APP_LOADER_SCRIPT"].includes(key) ? raw : esc(raw);
    html = html.replaceAll(`{{${key}}}`, () => value);
  }
  const leftovers = html.match(/\{\{[A-Z_]+\}\}/g);
  if (leftovers) throw new Error(`Unreplaced placeholders in ${meta.path}: ${leftovers.join(", ")}`);
  const relative = meta.path === "/" ? "index.html" : `${meta.path.slice(1)}index.html`;
  const output = path.join(ROOT, relative);
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, html);
  generated.push(relative);
  console.log(`prerendered ${meta.path} -> ${relative}`);
}

console.log(`prerender: ${generated.length} localized routes emitted`);
